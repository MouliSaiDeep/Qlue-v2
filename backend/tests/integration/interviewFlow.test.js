const {DocumentBoundary}=require('../helpers/documentBoundary');
const ddb=require('../../src/lib/dynamodb');
const {mockClient}=require('aws-sdk-client-mock');
const {BedrockRuntimeClient,ConverseCommand}=require('@aws-sdk/client-bedrock-runtime');
const {LambdaClient,InvokeCommand}=require('@aws-sdk/client-lambda');
const bedrock=mockClient(BedrockRuntimeClient),lambda=mockClient(LambdaClient);
const initialize=require('../../src/handlers/interview/initializeSession');
const input=require('../../src/handlers/interview/processUserInput');
const reports=require('../../src/handlers/feedback/generateFeedbackReport');
const sessions=require('../../src/models/session');
const storage=require('../../src/handlers/feedback/storeFeedbackReport');
let db;
beforeEach(()=>{db=new DocumentBoundary();jest.spyOn(ddb.docClient,'send').mockImplementation(c=>db.send(c));db.seed('qlue-users',{userId:'u',displayName:'Tester'});bedrock.reset();lambda.reset();lambda.on(InvokeCommand).resolves({});});
afterEach(()=>jest.restoreAllMocks());
test('real initialization, answer acceptance, report generation and persistence agree on one session',async()=>{
 const result=await initialize.handler({requestContext:{authorizer: {emailVerified: true, uid:'u'}},body:JSON.stringify({moduleType:'HR'})});
 expect(result.statusCode).toBe(200);const sessionId=JSON.parse(result.body).sessionId;
 await sessions.updateSessionState(sessionId,'LOADING_CONTEXT','INITIALIZING');
 const answer=await input.handler({requestContext:{authorizer: {emailVerified: true, uid:'u'}},body:JSON.stringify({sessionId,textTranscript:'I am a software engineer.',clientTurnId:'one'})});
 expect(answer.statusCode).toBe(200);expect(db.get('qlue-sessions',{sessionId}).answeredCount).toBe(1);
 await sessions.updateSessionState(sessionId,'TERMINATED','LOADING_CONTEXT');
 bedrock.on(ConverseCommand).resolves({output:{message:{content:[{text:JSON.stringify({strengths:['Communication'],improvements:['Be specific'],summary:'Good interview'})}]}},usage:{inputTokens:10,outputTokens:10}});
 process.env.STORE_FEEDBACK_REPORT_LAMBDA='store';
 const assessment=require('../../src/lib/feedbackAssessment');
 const prepared=assessment.prepare({moduleType:'HR',answerPairs:[{answerId:'one',question:'Describe your role.',answer:'I am a software engineer.'}]});
 const evaluated=assessment.validate(JSON.stringify({answers:[{answerId:'one',levels:[1,0,1,2],evidenceIds:['e1','','e1','e1']}]}),prepared);
 expect(await reports.handler({sessionId,userId:'u',moduleType:'HR',assessmentResult:assessment.report(prepared,evaluated),metadata:{turnCount:1}})).toMatchObject({success:true});
 const command=lambda.commandCalls(InvokeCommand).at(-1).args[0].input;
 const payload=JSON.parse(Buffer.from(command.Payload).toString());
 const saved=await storage.handler(payload);
 expect(db.get('qlue-sessions',{sessionId}).feedbackId).toBe(saved.feedbackId);
 expect(db.get('qlue-sessions',{sessionId}).feedbackStatus).toBe('COMPLETE');
 expect(db.get('qlue-feedback',{feedbackId:saved.feedbackId}).notificationStatus).toBe('PENDING');
});
